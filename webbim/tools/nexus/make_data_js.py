"""nexus_data.json -> webbim/src/nexus_data.js: the digitised Nexus plans as one deflated JSON module.
Ids are given here, once: nodes N001…, cells C001…, levels L00…L16."""
import os, sys, json, zlib, base64
HERE = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.environ.get('NEXUS_WORK', os.getcwd()), 'nexus_data.json')
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '..', '..', 'src', 'nexus_data.js')
d = json.load(open(src))
NID = lambda i: 'N%03d' % (i + 1)
CID = lambda i: 'C%03d' % (i + 1)
LID = lambda L: 'L%02d' % L
nodes = {NID(i): [int(p[0]), int(p[1])] for i, p in enumerate(d['nodes'])}
cells = {CID(i): [NID(n) for n in loop] for i, loop in enumerate(d['cells'])}
levels, use, ref = [], {}, {}
top = max(lv['level'] for lv in d['levels'])
for lv in d['levels']:
    L = lv['level']
    levels.append({'id': LID(L), 'name': LID(L), 'elevation': lv['elevation'], 'source': 'A2_2000_L%d.pdf' % L})
    use[LID(L)] = {CID(int(k)): v for k, v in sorted(lv['used'].items(), key=lambda kv: int(kv[0]))}
    ref[LID(L)] = {
        'zones': [{'c': z['color'], 'l': z.get('label', ''), 'p': z['pts']} for z in lv['zones']],
        'outlines': [{'closed': o['closed'], 'p': o['pts']} for o in lv['outlines']],
        'labels': [{'t': l['text'], 'at': l['at']} for l in lv['labels']] + [{'t': ('FOH' if l['kind'] == 'FOH' else 'SVC'), 'at': l['at'], 'lift': True} for l in lv['lifts']],
    }
vertical = []
for v in d['vertical']:
    base, t = v['base'], v['top']
    if v['use'] == 'Atrium': t = min(top, max(t, base + 1))      # a court is one storey deep at least: it cuts the slabs above its floor
    rec = {'use': v['use'], 'label': v['label'], 'at': v['at'], 'base': LID(base), 'top': LID(t)}
    if v.get('cars'): rec['cars'] = v['cars']
    if v.get('outline'): rec['outline'] = v['outline']
    vertical.append(rec)
data = {'scale': d['scale'], 'site': d['site'], 'setback': d['setback'], 'nodes': nodes, 'cells': cells, 'levels': levels, 'use': use, 'reference': ref, 'vertical': vertical}
raw = json.dumps(data, separators=(',', ':')).encode()
co = zlib.compressobj(9, zlib.DEFLATED, -15); z = co.compress(raw) + co.flush()
b64 = base64.b64encode(z).decode()
js = '''//! GENERATED by tools/nexus/make_data_js.py - do not edit by hand; rerun the tools (tools/nexus/README.md).
//! The Nexus level plans (A2_2000_L0 … L16, drawn at 1:2000) digitised: the 2D mesh that drives the slabs and
//! walls (nodes N…, cells C…), which cells each level uses (1 = the whole cell; [s, dx, dy] = the cell scaled by s
//! about its centroid and moved by dx, dy mm, where a drawn plate covers part of it), the drawn plates, zones and
//! labels kept as a reference to check the mesh against, the lifts, atria and risers the plans name, and the
//! site boundary. Model mm, y up, the origin at the site's north-west corner.

import { inflateBase64 } from "./inflate.js";
const NX_DATA_Z = "%s";
let NX_DATA_CACHE = null;
/** The digitised plans (a fresh copy each call: the sample edits what it is given). */
export function nexusData() {
  if (!NX_DATA_CACHE) NX_DATA_CACHE = inflateBase64(NX_DATA_Z);
  return JSON.parse(NX_DATA_CACHE);
}
''' % b64
open(dst, 'w').write(js)
print('json', len(raw), 'deflated', len(z), 'module', len(js), '->', os.path.abspath(dst))
print('levels', len(levels), 'nodes', len(nodes), 'cells', len(cells), 'vertical', len(vertical))
